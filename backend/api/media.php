<?php
/**
 * Turn stored localhost / relative upload paths into live site URLs.
 */
function publicSiteBase(): string {
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https');
    $scheme = $https ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
    return $scheme . '://' . $host;
}

function rewriteMediaUrl(?string $url): ?string {
    if ($url === null || $url === '') {
        return $url;
    }
    if (preg_match('{/uploads/[^/?#]+$}', $url, $m)) {
        return publicSiteBase() . $m[0];
    }
    if (strpos($url, 'localhost') !== false || strpos($url, '127.0.0.1') !== false) {
        $path = parse_url($url, PHP_URL_PATH);
        if ($path) {
            return publicSiteBase() . $path;
        }
    }
    return $url;
}

function isAdminUpload(?string $url): bool {
    return is_string($url) && preg_match('#/uploads/#i', $url);
}

function isGenericMedia(?string $url): bool {
    if ($url === null || $url === '') {
        return true;
    }
    return (bool) preg_match('/localhost|127\.0\.0\.1|default-category|cat-office\.jpg|cat-windows\.jpg|cat-antivirus\.jpg|cat-creative\.jpg|product-default/i', $url);
}

/**
 * Path to the generated product asset for a slug, relative to site root.
 * Generated by scripts/generate-product-assets.py -> backend/uploads/products/{slug}.jpg
 *
 * Physical layout in production (cPanel):
 *   /public_html/backend/uploads/products/{slug}.jpg   <- on disk
 *   https://shop.hedztech.com/uploads/products/{slug}.jpg  <- served URL
 * (the /uploads/ -> /backend/uploads/ rewrite is in .htaccess)
 *
 * In local dev the PHP server is started with -t backend, so the doc root IS
 * backend/ and the file is at {docroot}/uploads/products/{slug}.jpg.
 */
function generatedAssetPath(string $slug): string {
    if ($slug === '') {
        return '';
    }
    $rel = '/uploads/products/' . $slug . '.jpg';
    $docroot = realpath($_SERVER['DOCUMENT_ROOT'] ?? '');
    $candidates = [];
    if ($docroot) {
        // Production: docroot/backend/uploads/products/{slug}.jpg
        $candidates[] = $docroot . '/backend' . $rel;
        // Dev (-t backend): docroot/uploads/products/{slug}.jpg
        $candidates[] = $docroot . $rel;
    }
    // Always also check relative to this file's project root.
    $candidates[] = dirname(__DIR__, 1) . $rel;
    foreach ($candidates as $fs) {
        if ($fs && is_file($fs)) {
            return $rel;
        }
    }
    return '';
}

function coverUrl(string $title, string $slug = ''): string {
    // cover.php lives at backend/api/cover.php (served via /backend/api/cover.php).
    // Must match the real file path - /backend/cover.php does not exist and 404s.
    return publicSiteBase() . '/backend/api/cover.php?title=' . rawurlencode($title) . '&slug=' . rawurlencode($slug);
}

