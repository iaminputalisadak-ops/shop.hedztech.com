/**
 * Resolve an on-disk path for a stored /uploads/... or /assets/... URL.
 * Production: /public_html/backend/uploads/{file}   (served at /uploads/{file} or /assets/{file})
 * Dev (-t backend): {docroot}/uploads/{file}
 * Returns the real filesystem path, or '' if it cannot be resolved.
 */
function uploadFsPath(string $url): string {
    if (preg_match('{/(?:uploads|assets)/([^/?#]+)$}', $url, $m)) {
        $file = $m[1];
        $docroot = realpath($_SERVER['DOCUMENT_ROOT'] ?? '');
        $candidates = [];
        if ($docroot) {
            $candidates[] = $docroot . '/backend/uploads/' . $file;
            $candidates[] = $docroot . '/uploads/' . $file;
            $candidates[] = $docroot . '/assets/' . $file;
        }
        $candidates[] = dirname(__DIR__, 1) . '/uploads/' . $file;
        foreach ($candidates as $fs) {
            if ($fs && is_file($fs)) {
                return $fs;
            }
        }
    }
    return '';
}

function productImageUrl(?string $url, string $name, string $slug = ''): string {
    // 0. Drop broken dev/localhost references - they 404 in production.
    if ($url !== null && $url !== '' && (
        strpos($url, 'localhost') !== false
        || strpos($url, '127.0.0.1') !== false
        || strpos($url, '/Nepal-TechGuard/') !== false
    )) {
        $url = null;
    }

    // 1. Genuine admin upload (stored /uploads/... path) -> rewrite to live domain,
    //    but ONLY if the physical file actually exists. A dangling admin upload
    //    is treated as missing and falls through to the generated asset.
    if (isAdminUpload($url)) {
        if (uploadFsPath($url) !== '') {
            return rewriteMediaUrl($url);
        }
        $url = null;
    }

    // 2. Any other non-empty URL that is already a real hosted image.
    //    If it references a local /uploads/ or /assets/ path, verify the file
    //    exists before trusting it - otherwise fall through to the generated asset.
    if ($url !== null && $url !== '' && strpos($url, 'cover.php') === false) {
        if (preg_match('{/(?:uploads|assets)/}i', $url) && uploadFsPath($url) === '') {
            $url = null; // dangling local path -> treat as missing
        }
        if ($url !== null) {
            return $url;
        }
    }

    // 3. A generated product asset exists for this slug -> use it.
    //    This is the primary integration point for the Pillow-generated catalog images.
    $asset = generatedAssetPath($slug);
    if ($asset !== '') {
        return publicSiteBase() . $asset;
    }

    // 4. Fallback: dynamic SVG cover (always valid, never 404s).
    return coverUrl($name !== '' ? $name : 'Software License', $slug);
}

function categoryImageUrl(?string $url, string $name, string $slug = ''): string {
    if (isAdminUpload($url)) {
        return rewriteMediaUrl($url);
    }
    $file = categoryCoverFile($slug);
    if ($file) {
        return publicSiteBase() . $file;
    }
    return coverUrl($name !== '' ? $name : $slug, $slug);
}
