#!/usr/bin/env python3
"""Integrate generated product images into the catalog.

Reads scripts/data/products-live.json (source of truth), checks which products
already have a genuine image URL, maps every remaining product to its generated
asset at backend/uploads/products/{slug}.jpg, and emits:
  - backend/uploads/products/_integration_manifest.json  (audit trail)
  - backend/uploads/products/_update_image_urls.sql       (safe DB UPDATE script)

The SQL is generated but NOT executed automatically - MySQL is not reachable
from this machine, so a human runs it when the DB is available.

Usage: python scripts/integrate_product_images.py
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LIVE = os.path.join(ROOT, "scripts", "data", "products-live.json")
ASSET_DIR = os.path.join(ROOT, "backend", "uploads", "products")
MANIFEST_PATH = os.path.join(ASSET_DIR, "_integration_manifest.json")
SQL_PATH = os.path.join(ASSET_DIR, "_update_image_urls.sql")


def is_genuine(url: str) -> bool:
    """A URL is genuine if it is a real hosted image, not a localhost path or cover.php."""
    if not url:
        return False
    if "localhost" in url or "127.0.0.1" in url:
        return False
    if "cover.php" in url:
        return False
    # Real uploads/assets are served under /uploads/ or /assets/
    return "/uploads/" in url or "/assets/" in url


def main() -> int:
    if not os.path.exists(LIVE):
        print("ERROR: products-live.json not found at", LIVE)
        return 1
    os.makedirs(ASSET_DIR, exist_ok=True)

    with open(LIVE, encoding="utf-8") as f:
        products = json.load(f)

    kept = generated = fallback = 0
    manifest = []
    sql_rows = []

    for p in products:
        pid = p["id"]
        slug = p.get("slug") or ""
        name = p.get("name") or ""
        existing = (p.get("image_url") or "").strip()
        asset_file = os.path.join(ASSET_DIR, slug + ".jpg")

        if is_genuine(existing):
            kept += 1
            manifest.append({
                "product_id": pid,
                "slug": slug,
                "name": name,
                "image": existing,
                "source": "existing_preserved",
                "method": "n/a",
                "verified": "yes",
            })
            continue

        if os.path.exists(asset_file):
            url = "/uploads/products/" + slug + ".jpg"
            generated += 1
            sql_rows.append((pid, slug, name, url))
            manifest.append({
                "product_id": pid,
                "slug": slug,
                "name": name,
                "image": url,
                "source": "generated_pillow",
                "method": "Pillow programmatic (scripts/generate-product-assets.py)",
                "verified": "yes",
            })
        else:
            fallback += 1
            manifest.append({
                "product_id": pid,
                "slug": slug,
                "name": name,
                "image": "cover.php fallback",
                "source": "cover_php_fallback",
                "method": "n/a",
                "verified": "no",
            })

    with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2, ensure_ascii=False)

    with open(SQL_PATH, "w", encoding="utf-8") as f:
        f.write("-- Product image URL update. Generated by scripts/integrate_product_images.py\n")
        f.write("-- Safe to run: only updates image_url, preserves all other columns and rows.\n")
        f.write("-- Run when MySQL is available:\n")
        f.write("--   mysql -u root nepal_techguard < backend/uploads/products/_update_image_urls.sql\n\n")
        f.write("START TRANSACTION;\n")
        for pid, slug, name, url in sql_rows:
            esc = name.replace("'", "''")
            f.write(f"UPDATE products SET image_url = '{url}' WHERE id = {pid} AND name = '{esc}';\n")
        f.write("COMMIT;\n")

    print(f"products: {len(products)}")
    print(f"  existing preserved : {kept}")
    print(f"  generated mapped  : {generated}")
    print(f"  cover.php fallback: {fallback}")
    print(f"manifest : {MANIFEST_PATH}")
    print(f"sql      : {SQL_PATH} ({len(sql_rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())